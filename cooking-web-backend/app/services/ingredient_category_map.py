def find_category_keywords(ingredient: str) -> list[str]:
  """
  食材名に対応するカテゴリ候補キーワードを返す（該当なしは空リスト）
  完全一致を優先し、なければ食材名に含まれる最長のキー・別名を採用する
  （例: 「国産豚バラ肉」→「豚バラ」、「新たまねぎ」→「玉ねぎ」）
  """
  name = ingredient.strip()
  key = INGREDIENT_ALIASES.get(name, name)
  if key in INGREDIENT_CATEGORY_KEYWORDS:
    return INGREDIENT_CATEGORY_KEYWORDS[key]

  # 部分一致は長いものを優先し、「ねぎ」が「玉ねぎ」を奪うような誤マッチを防ぐ
  # (一致した文字列の長さ, 対応表のキー)
  candidates = [(len(k), k) for k in INGREDIENT_CATEGORY_KEYWORDS if k in name]
  candidates += [(len(a), INGREDIENT_ALIASES[a]) for a in INGREDIENT_ALIASES if a in name]
  if not candidates:
    return []
  _, longest = max(candidates, key=lambda c: c[0])
  return INGREDIENT_CATEGORY_KEYWORDS[longest]
